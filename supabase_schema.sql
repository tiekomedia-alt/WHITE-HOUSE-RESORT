-- 1. Create the table for storing tour requests
create table public.tour_requests (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  full_name text not null,
  email text not null,
  phone text,
  date date,
  party_size integer,
  special_requests text
);

-- 2. Enable Row Level Security (RLS)
-- This protects your table so you can define specific rules for access.
alter table public.tour_requests enable row level security;

-- 3. Create a Policy to allow public (anonymous) inserts
-- This is required for your public website form to be able to save data to this table.
create policy "Allow public form submissions"
on public.tour_requests
for insert
to anon
with check (true);

-- Note: We are NOT adding a SELECT policy for 'anon'.
-- This ensures that while the public can *write* to the table, they cannot *read* (download) your customer data.
