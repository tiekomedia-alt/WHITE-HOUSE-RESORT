-- This script safely resets the permissions for the form.

-- 1. Ensure the table exists
create table if not exists public.tour_requests (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  full_name text not null,
  email text not null,
  phone text,
  date date,
  party_size integer,
  special_requests text
);

-- 2. Enable Row Level Security (RLS)
alter table public.tour_requests enable row level security;

-- 3. Reset Policies (Drop old ones to avoid errors)
drop policy if exists "Allow public form submissions" on public.tour_requests;
drop policy if exists "Allow public insert" on public.tour_requests;

-- 4. Create the correct Policy for Anonymous Inserts
create policy "Allow public form submissions"
on public.tour_requests
for insert
to anon
with check (true);

-- 5. Explicitly Grant Usage and Insert permissions
-- This ensures the 'anon' role has the basic SQL rights to access the table
grant usage on schema public to anon;
grant insert on table public.tour_requests to anon;
